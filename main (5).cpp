    // 2. Знаменник (нижня частина дробу)
    double denominator = std::cbrt(
        std::abs(
            std::sin(x * x) + 0.25 * (std::log(std::abs(x * x - 2.5)) / std::log(5))
        )
    );

    // 3. Обчислення y
